"""Pack a game's recorded music into one script the page can load from disk.

Reads the game's ``tunes.yaml`` and the takes in its ``tunes/`` folder, and
for each take: the effects' retro recipe (mono, the lows and highs rolled
off, a touch of saturation), a fade over its last seconds, one loudness, a
small MP3. Everything goes into ``tunes.js`` as base64, as ``effects.js``.

Example:
    packed = build(tune_set, game_dir / "tunes")
    write_js(packed, tune_set, game_dir / "game/tunes.js")
"""

from __future__ import annotations

import base64
import json
import tempfile
from dataclasses import dataclass
from pathlib import Path

from config import TUNE_FADE_S, TUNE_LOUDNESS_DB, TUNE_MAX_SECONDS
from effects import prepare, retro
from samples import SampleError
from schema.tunes import TuneSet


@dataclass
class Packed:
    """One packed take, as the game sees it."""

    tune: str
    file: str
    gain_db: float  # what levelling did to it
    data: bytes


def recipe() -> str:
    """The ffmpeg filters every music take goes through before levelling:
    cut to the longest allowed, faded out at its own end (reversed, faded in,
    reversed back, so the fade needs no length), then the retro recipe."""
    return ",".join(
        [
            f"atrim=0:{TUNE_MAX_SECONDS}",
            "areverse",
            f"afade=t=in:d={TUNE_FADE_S}",
            "areverse",
            *retro(),
        ]
    )


def build(tune_set: TuneSet, folder: Path) -> list[Packed]:
    """Prepare every take in the set, read from ``folder``."""
    missing = [
        t.file
        for tune in tune_set.tunes
        for t in tune.takes
        if not (folder / t.file).is_file()
    ]
    if missing:
        raise SampleError(f"takes not found in {folder}: {missing} — check tunes.yaml")
    packed = []
    with tempfile.TemporaryDirectory() as tmp:
        for i, (tune, take) in enumerate(
            (part, t) for part in tune_set.tunes for t in part.takes
        ):
            out = Path(tmp) / f"{i}.mp3"
            gain = prepare(folder / take.file, out, recipe(), TUNE_LOUDNESS_DB)
            packed.append(Packed(tune.id, take.file, gain, out.read_bytes()))
    return packed


def write_js(packed: list[Packed], tune_set: TuneSet, out: Path) -> Path:
    """Write ``tunes.js``: a global TUNES of {part: [base64 mp3]}."""
    table: dict[str, list[str]] = {}
    for p in packed:
        table.setdefault(p.tune, []).append(base64.b64encode(p.data).decode("ascii"))
    out.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "// Generated by `main.py tunes` from tunes.yaml — do not edit.\n"
        f"// {tune_set.source}\n"
        "/* exported TUNES */\n"
    )
    out.write_text(
        header + "const TUNES = " + json.dumps(table) + "\n", encoding="utf-8"
    )
    return out
